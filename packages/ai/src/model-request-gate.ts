/**
 * ModelRequestGate: a generic, additive hook that lets one registered owner
 * decide whether an outbound model request may leave the process.
 *
 * Nothing here knows what the owner decides on (any policy at all).
 * With no gate registered, or a gate that answers `pass`, every request path
 * behaves exactly as it did before this module existed.
 *
 * The trusted parts of an attempt (`origin`, `scope`) are never supplied by a
 * caller: the core derives them from its own execution context
 * (`model-request-execution.ts`, internal). A request that carries no valid
 * context is classified `standalone` (process explicitly marked as a
 * session-less command) or `unclassified`, and the gate is told which.
 */
import { getModelRequestRuntime } from "./model-request-runtime";

export * from "./error/model-request-denied";

export type ModelRequestKind =
	| "chat"
	| "judgment"
	| "embedding"
	| "rerank"
	| "image"
	| "speech"
	| "transcription"
	| "video";

/** Purpose declared by the call site. The core never interprets it. */
export type ModelRequestPurpose =
	| "main"
	| "subagent"
	| "advisor"
	| "side-channel"
	| "compaction"
	| "branch-summary"
	| "handoff"
	| "judge"
	| "memory"
	| "title"
	| "auto-repair"
	| "commit"
	| "annotate"
	| "speech-enhance"
	| "cache-warm"
	| "embedding"
	| "other";

export interface ModelRequestAgent {
	readonly id: string;
	readonly kind: "main" | "sub";
	readonly name: string;
	readonly depth: number;
	readonly parentId?: string;
}

export interface ModelRequestScope {
	/**
	 * Id of the root session the user started or resumed. A root is its own root; children receive it
	 * explicitly from the core. Never inferred from a `parentSession` header. `undefined` means a child
	 * was created without an explicit root.
	 */
	readonly rootSessionId: string | undefined;
	/** Session that issued the request. */
	readonly sessionId: string;
	readonly agent: ModelRequestAgent;
	readonly purpose: ModelRequestPurpose;
}

export type ModelRequestReason =
	| "first"
	| "provider-retry"
	| "auth-rotation"
	| "thinking-loop-retry"
	| "oneshot-retry"
	| "turn-retry"
	| "model-fallback"
	| "judge-candidate"
	| "judge-attempt"
	| "replay";

export interface ModelRequestWire {
	readonly method: string;
	/** Credential-bearing query parameters are removed by the core. */
	readonly url: string;
	/** Authorization, x-api-key, cookie and similar credentials are removed by the core. */
	readonly headers: Readonly<Record<string, string>>;
	/** Byte length of the body actually sent. */
	readonly bodyBytes: number;
	/** In-memory only. A gate must never persist or log what this returns. */
	readBody(): Promise<Uint8Array>;
}

export interface ModelRequestModelRef {
	readonly provider: string;
	readonly id: string;
	readonly api: string;
	readonly baseUrl?: string;
}

export interface ModelRequestAttempt {
	/** Generated by the core per wire attempt; idempotency key of `authorize`. */
	readonly attemptId: string;
	/** Id of the logical request (one `stream`/`complete` call). */
	readonly requestId: string;
	readonly retryOf?: string;
	readonly reason: ModelRequestReason;
	/**
	 * Decided by the core, never by the caller. `session`: inside a valid core execution context.
	 * `standalone`: the process was marked a session-less command by the core. `unclassified`: neither.
	 */
	readonly origin: "session" | "standalone" | "unclassified";
	/** Present exactly when `origin` is `session`. */
	readonly scope: ModelRequestScope | undefined;
	readonly kind: ModelRequestKind;
	readonly model: ModelRequestModelRef;
	/** `undefined` when the transport's body cannot be read (WebSocket, SDK, streaming body, FormData). */
	readonly wire: ModelRequestWire | undefined;
	readonly signal?: AbortSignal;
}

export type ModelRequestOutcome =
	| { readonly type: "not-sent"; readonly aborted: boolean }
	| {
			readonly type: "request-failed";
			readonly sent: "no" | "maybe";
			readonly aborted: boolean;
			readonly transportClosed: boolean;
	  }
	| { readonly type: "response-ended"; readonly status: number }
	| {
			readonly type: "response-failed";
			readonly status?: number;
			readonly aborted: boolean;
			readonly transportClosed: boolean;
	  };

export interface ModelRequestLease {
	/** Called synchronously immediately before the first I/O. In-memory transition only. */
	beginSend(): void;
	observeResponse(head: { readonly status: number; readonly headers: Readonly<Record<string, string>> }): void;
	/** The core tees the response body to the gate without altering it. */
	observeChunk(chunk: Uint8Array): void;
	/** Exactly once per attempt; the core guarantees it in a `finally`. */
	settle(outcome: ModelRequestOutcome): Promise<void>;
}

export type ModelRequestDecision =
	| { readonly type: "pass" }
	| { readonly type: "allow"; readonly lease: ModelRequestLease }
	| { readonly type: "deny"; readonly code: string; readonly message: string };

export interface ModelRequestGate {
	authorize(attempt: ModelRequestAttempt): Promise<ModelRequestDecision>;
}

export interface ModelRequestGateOptions {
	/**
	 * Longest the core waits for `authorize` before it treats the gate as unresponsive and denies with
	 * `gate-error`. Positive safe integer milliseconds, at most 2_147_483_647 (the longest delay a platform timer
	 * honors; a larger value would fire immediately). There is no default: without it the core waits until
	 * the request's own signal aborts, and in neither case does any I/O start.
	 */
	readonly authorizeTimeoutMs?: number;
}

export type ModelRequestSiteStatus = "gated" | "context-inherited" | "uncovered";

/**
 * How a site receives the core execution context. `unverified` means no evidence either way, and is never
 * treated as covered.
 */
export type ModelRequestContextPropagation =
	| "installed"
	| "inherited"
	| "explicit-bind"
	| "standalone-mark"
	| "not-carried"
	| "unverified";

export interface ModelRequestCoverageSite {
	readonly id: string;
	readonly location: string;
	readonly status: ModelRequestSiteStatus;
	readonly contextPropagation: ModelRequestContextPropagation;
	/** Why the site is not `gated`/`context-inherited`; empty when it is. */
	readonly reason: string;
}

export interface ModelRequestCoverage {
	readonly sites: readonly ModelRequestCoverageSite[];
	/** True only when no site is `uncovered` and the context mechanism's self-check passed. */
	readonly complete: boolean;
	/** Result of the context mechanism's self-check (await/timer/nesting/emitter/forgery behavior). */
	readonly contextCheck: "pending" | "passed" | "failed";
	/** Digest of the site table (ids, statuses, propagation). Changes whenever the inventory changes. */
	readonly inventoryVersion: string;
}

export interface ModelRequestGateInfo {
	readonly apiVersion: 1;
	readonly registered: boolean;
	readonly coverage: ModelRequestCoverage;
}

/**
 * Register the process's gate. Re-registering the same gate under the same owner with the same options
 * is a no-op; anything else throws. There is no way to unregister (latch), so a gate cannot be removed
 * midway to make later requests pass unchecked.
 */
export function registerModelRequestGate(owner: string, gate: ModelRequestGate, options?: ModelRequestGateOptions): void {
	getModelRequestRuntime().registerGate(owner, gate, options);
}

export function getModelRequestGateInfo(): ModelRequestGateInfo {
	return getModelRequestRuntime().gateInfo();
}

/**
 * Run (or await) the self-check of the execution-context mechanism. Resolves to whether it passed;
 * `getModelRequestGateInfo().coverage.contextCheck` reflects the result afterwards.
 */
export function verifyModelRequestContext(): Promise<boolean> {
	return getModelRequestRuntime().verifyContext();
}
